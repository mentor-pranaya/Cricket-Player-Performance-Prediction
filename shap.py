import pandas as pd
import numpy as np
import shap
import pickle
import matplotlib.pyplot as plt

# Load data
batsman = pd.read_csv("final_batsman_features.csv")
bowler = pd.read_csv("final_bowler_features.csv")

batsman["match_date"] = pd.to_datetime(batsman["match_date"])
bowler["match_date"] = pd.to_datetime(bowler["match_date"])

batsman = batsman.sort_values("match_date")
bowler = bowler.sort_values("match_date")

# Features
batsman_features = [
    "career_avg_runs","venue_avg_runs","opponent_avg_runs",
    "prev_10_avg_runs","strike_rate","fours","sixes"
]

bowler_features = [
    "career_avg_wkts","venue_avg_wkts","opponent_avg_wkts",
    "prev_10_avg_wkts","economy"
]

# Train-test split (chronological)
split_bat = int(len(batsman)*0.8)
split_bowl = int(len(bowler)*0.8)

X_test_bat = batsman[batsman_features].iloc[split_bat:]
X_test_bowl = bowler[bowler_features].iloc[split_bowl:]

# Load trained models
xgb_bat = pickle.load(open("best_batsman_model.pkl","rb"))
xgb_bowl = pickle.load(open("best_bowler_model.pkl","rb"))

# Create SHAP Explainers
explainer_bat = shap.TreeExplainer(xgb_bat)
explainer_bowl = shap.TreeExplainer(xgb_bowl)

shap_values_bat = explainer_bat.shap_values(X_test_bat)
shap_values_bowl = explainer_bowl.shap_values(X_test_bowl)

# ---------------- GLOBAL IMPORTANCE ----------------

print("Batsman Global Feature Importance")
shap.summary_plot(shap_values_bat, X_test_bat)

print("Bowler Global Feature Importance")
shap.summary_plot(shap_values_bowl, X_test_bowl)

# ---------------- BAR PLOT (Cleaner for Reports) ----------------

print("Batsman Feature Importance (Bar)")
shap.summary_plot(shap_values_bat, X_test_bat, plot_type="bar")

print("Bowler Feature Importance (Bar)")
shap.summary_plot(shap_values_bowl, X_test_bowl, plot_type="bar")

# ---------------- LOCAL EXPLANATION ----------------

print("Example Batsman Prediction Explanation")
shap.force_plot(
    explainer_bat.expected_value,
    shap_values_bat[0],
    X_test_bat.iloc[0],
    matplotlib=True
)

print("Example Bowler Prediction Explanation")
shap.force_plot(
    explainer_bowl.expected_value,
    shap_values_bowl[0],
    X_test_bowl.iloc[0],
    matplotlib=True
)
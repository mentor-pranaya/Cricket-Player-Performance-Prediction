import pandas as pd
import numpy as np

deliveries = pd.read_csv("deliveries_updated_ipl_upto_2025.csv")
matches = pd.read_csv("matches_updated_ipl_upto_2025.csv")

deliveries.columns = deliveries.columns.str.lower().str.strip()
matches.columns = matches.columns.str.lower().str.strip()

match_id_del = [col for col in deliveries.columns if "match" in col and "id" in col][0]
match_id_mat = [col for col in matches.columns if "match" in col and "id" in col or col=="id"][0]

deliveries = deliveries.rename(columns={match_id_del: "match_id"})
matches = matches.rename(columns={match_id_mat: "match_id"})

df = deliveries.merge(matches, on="match_id", how="left")

date_col = [col for col in df.columns if "date" in col][0]
df["match_date"] = pd.to_datetime(df[date_col], errors="coerce")

numeric_cols = ["batsman_runs","extras","total_runs","iswide","isnoball","byes","legbyes","penalty"]
for col in numeric_cols:
    if col in df.columns:
        df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0)

df = df.dropna(subset=["batsman","bowler","batting_team","bowling_team"])

df["legal_ball"] = np.where(
    (df.get("iswide",0)==0) & (df.get("isnoball",0)==0),
    1,0
)

df["total_runs"] = df.get("batsman_runs",0) + df.get("extras",0)

df = df.sort_values(["match_id","inning","over","ball"])

batsman_match = df.groupby([
    "match_id","match_date","venue","batsman","batting_team","bowling_team"
]).agg(
    runs_scored=("batsman_runs","sum"),
    balls_faced=("legal_ball","sum"),
    fours=("batsman_runs",lambda x: (x==4).sum()),
    sixes=("batsman_runs",lambda x: (x==6).sum())
).reset_index()

batsman_match["strike_rate"] = np.where(
    batsman_match["balls_faced"]>0,
    (batsman_match["runs_scored"]/batsman_match["balls_faced"])*100,
    0
)

wicket_types = ["bowled","caught","lbw","stumped","caught and bowled","hit wicket"]

bowler_match = df.groupby([
    "match_id","match_date","venue","bowler","bowling_team","batting_team"
]).agg(
    runs_conceded=("total_runs","sum"),
    legal_balls=("legal_ball","sum"),
    wickets=("dismissal_kind",lambda x: x.isin(wicket_types).sum())
).reset_index()

bowler_match["overs_bowled"] = bowler_match["legal_balls"]/6

bowler_match["economy"] = np.where(
    bowler_match["overs_bowled"]>0,
    bowler_match["runs_conceded"]/bowler_match["overs_bowled"],
    0
)

batsman_match = batsman_match.sort_values(["batsman","match_date"])
bowler_match = bowler_match.sort_values(["bowler","match_date"])

batsman_match["prev_10_avg_runs"] = batsman_match.groupby("batsman")["runs_scored"].transform(
    lambda x: x.shift().rolling(10,min_periods=1).mean()
)

bowler_match["prev_10_avg_wkts"] = bowler_match.groupby("bowler")["wickets"].transform(
    lambda x: x.shift().rolling(10,min_periods=1).mean()
)

batsman_match = batsman_match.fillna(0)
bowler_match = bowler_match.fillna(0)

batsman_match.to_csv("model_dataset_batsman.csv", index=False)
bowler_match.to_csv("model_dataset_bowler.csv", index=False)

print("Batsman Dataset Shape:", batsman_match.shape)
print("Bowler Dataset Shape:", bowler_match.shape)
import pandas as pd
import numpy as np

batsman = pd.read_csv("model_dataset_batsman.csv")
bowler = pd.read_csv("model_dataset_bowler.csv")
deliveries = pd.read_csv("deliveries_updated_ipl_upto_2025.csv")
matches = pd.read_csv("matches_updated_ipl_upto_2025.csv")

deliveries.columns = deliveries.columns.str.lower().str.strip()
matches.columns = matches.columns.str.lower().str.strip()

match_id_del = [c for c in deliveries.columns if "match" in c and "id" in c][0]
match_id_mat = [c for c in matches.columns if "match" in c and "id" in c or c=="id"][0]

deliveries = deliveries.rename(columns={match_id_del: "match_id"})
matches = matches.rename(columns={match_id_mat: "match_id"})

df = deliveries.merge(matches, on="match_id", how="left")

df["total_runs"] = df.get("batsman_runs",0) + df.get("extras",0)

wicket_types = ["bowled","caught","lbw","stumped","caught and bowled","hit wicket"]
df["is_wicket"] = df["dismissal_kind"].isin(wicket_types).astype(int)

# ---------------- Batsman Features ----------------

batsman["career_avg_runs"] = batsman.groupby("batsman")["runs_scored"].transform("mean")

venue_avg = batsman.groupby(["batsman","venue"])["runs_scored"].mean().reset_index()
venue_avg = venue_avg.rename(columns={"runs_scored":"venue_avg_runs"})
batsman = batsman.merge(venue_avg,on=["batsman","venue"],how="left")

opp_avg = batsman.groupby(["batsman","bowling_team"])["runs_scored"].mean().reset_index()
opp_avg = opp_avg.rename(columns={"runs_scored":"opponent_avg_runs"})
batsman = batsman.merge(opp_avg,on=["batsman","bowling_team"],how="left")

# Safe H2H (mean runs conceded by bowler overall)
h2h_runs = df.groupby("bowler")["batsman_runs"].mean().reset_index()
h2h_runs = h2h_runs.rename(columns={"batsman_runs":"bowler_avg_runs_conceded"})
batsman = batsman.merge(h2h_runs,left_on="bowling_team",right_on="bowler",how="left")
batsman = batsman.drop(columns=["bowler"],errors="ignore")

# ---------------- Bowler Features ----------------

bowler["career_avg_wkts"] = bowler.groupby("bowler")["wickets"].transform("mean")

venue_wkts = bowler.groupby(["bowler","venue"])["wickets"].mean().reset_index()
venue_wkts = venue_wkts.rename(columns={"wickets":"venue_avg_wkts"})
bowler = bowler.merge(venue_wkts,on=["bowler","venue"],how="left")

opp_wkts = bowler.groupby(["bowler","batting_team"])["wickets"].mean().reset_index()
opp_wkts = opp_wkts.rename(columns={"wickets":"opponent_avg_wkts"})
bowler = bowler.merge(opp_wkts,on=["bowler","batting_team"],how="left")

# Safe H2H (average wickets per match)
h2h_wkts = bowler.groupby("bowler")["wickets"].mean().reset_index()
h2h_wkts = h2h_wkts.rename(columns={"wickets":"bowler_avg_wkts"})
bowler = bowler.merge(h2h_wkts,on="bowler",how="left")

batsman = batsman.fillna(0)
bowler = bowler.fillna(0)

print("Final Batsman Shape:", batsman.shape)
print("Final Bowler Shape:", bowler.shape)

batsman.to_csv("final_batsman_features.csv",index=False)
bowler.to_csv("final_bowler_features.csv",index=False)